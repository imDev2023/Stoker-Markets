#!/usr/bin/env python3
"""
The fonts a share card is set in (src/lib/ogFonts.ts), as subsets the web Worker can bundle.

A share card (opengraph-image.tsx at the app's root and under the coin page) is drawn by `next/og`, which lays text out
with Satori and so needs each font's bytes, in TTF or OTF: it cannot read the site's own woff2 files, and a Worker has
no file system to read a font from at request time. So the site's display and body faces are taken from Google Fonts as
static instances at the weights the cards use, cut down to the Latin ranges a coin's name and the site's copy are set
in, and written into a TypeScript module as base64, which every bundler carries without a loader. Run it again when a
card needs another weight or script; it needs fontTools (`pip install fonttools`).
"""
import base64
import re
import subprocess
import sys
from io import BytesIO
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

# The faces as the site sets them (globals.css): the display face for the wordmark, a pair and a headline, the body
# face for a name and a line of copy. Each at one static weight; Satori reads no variable axis.
FACES = [
    ("display", "Bricolage Grotesque", 700),
    ("display", "Bricolage Grotesque", 800),
    ("body", "Instrument Sans", 500),
]

# What a card can say: ASCII, Latin-1, Latin Extended-A, the general punctuation (quotes, dashes, the middle dot, the
# ellipsis), the euro and the trade mark sign. Anything else falls back to the default face at render time.
RANGES = "U+0020-007E,U+00A0-017F,U+2010-2027,U+2030-203A,U+20AC,U+2122,U+2212"

OUT = Path(__file__).resolve().parent.parent / "src" / "lib" / "ogFonts.ts"


def ttf_url(family: str, weight: int) -> str:
    """Google Fonts answers an unknown user agent with plain TTF files, one per requested weight."""
    css = subprocess.run(
        ["curl", "-sS", "-A", "", f"https://fonts.googleapis.com/css2?family={family.replace(' ', '+')}:wght@{weight}"],
        check=True, capture_output=True, text=True,
    ).stdout
    match = re.search(r"url\((https://fonts\.gstatic\.com/[^)]+\.ttf)\)", css)
    if not match:
        raise SystemExit(f"no TTF for {family} {weight} in Google Fonts' answer:\n{css}")
    return match.group(1)


def subset_font(data: bytes) -> bytes:
    options = subset.Options()
    options.flavor = None
    # The copyright, the licence and the names stay in the file, as the Open Font License asks.
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    options.notdef_outline = True
    font = TTFont(BytesIO(data))
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=subset.parse_unicodes(RANGES))
    subsetter.subset(font)
    out = BytesIO()
    font.save(out)
    return out.getvalue()


def main() -> None:
    entries = []
    for role, family, weight in FACES:
        url = ttf_url(family, weight)
        raw = subprocess.run(["curl", "-sS", url], check=True, capture_output=True).stdout
        cut = subset_font(raw)
        print(f"{family} {weight}: {len(raw):,} bytes from Google Fonts, {len(cut):,} as the subset", file=sys.stderr)
        entries.append((role, family, weight, url, base64.b64encode(cut).decode("ascii")))
    lines = [
        "// Generated by scripts/og-fonts.py: the share cards' fonts as Latin subsets, base64 so every bundler carries them.",
        "// Run the script again rather than editing this file.",
        "",
        "export type OgFont = { role: \"display\" | \"body\"; name: string; weight: 500 | 700 | 800; data: string };",
        "",
        "export const OG_FONTS: readonly OgFont[] = [",
    ]
    for role, family, weight, url, b64 in entries:
        lines.append(f"  // {url}")
        lines.append(f"  {{ role: \"{role}\", name: \"{family}\", weight: {weight}, data: \"{b64}\" }},")
    lines.append("];")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({OUT.stat().st_size:,} bytes)", file=sys.stderr)


if __name__ == "__main__":
    main()
