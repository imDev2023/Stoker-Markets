import { Keypair } from "@solana/web3.js";
import { signDataItem, parseDataItem, uploadDataItem, creditBalance, priceForBytes, wincForLamports, depositAddress } from "@launchpad/arweave";
const urls = { upload: "https://upload.services.ar-io.dev", payment: "https://payment.services.ar-io.dev" };
const kp = Keypair.fromSeed(new Uint8Array(32).fill(11));
const data = new TextEncoder().encode(JSON.stringify({ name: "spike", symbol: "SPK", t: Date.now() }));
const anchor = crypto.getRandomValues(new Uint8Array(32));
const item = await signDataItem(kp.secretKey, { data, tags: [{ name: "Content-Type", value: "application/json" }, { name: "App-Name", value: "stoker" }], anchor });
const again = await signDataItem(kp.secretKey, { data, tags: [{ name: "Content-Type", value: "application/json" }, { name: "App-Name", value: "stoker" }], anchor });
console.log("deterministic", item.id === again.id, item.bytes.length);
const parsed = await parseDataItem(item.bytes);
console.log("parsed", parsed.id === item.id, parsed.valid, parsed.tags, new TextDecoder().decode(parsed.data).slice(0, 40));
const tampered = item.bytes.slice(); tampered[tampered.length - 1] ^= 1;
console.log("tampered valid", (await parseDataItem(tampered)).valid);
const r = await uploadDataItem(urls, item.bytes);
console.log("uploaded", r.id === item.id, r.winc, r.dataCaches);
const r2 = await uploadDataItem(urls, item.bytes);
console.log("again", r2.id === item.id, r2.winc);
console.log("balance", await creditBalance(urls, kp.publicKey.toBase58()));
console.log("price 1MiB", await priceForBytes(urls, 1048576), "winc per SOL", await wincForLamports(urls, 1_000_000_000n));
console.log("deposit", await depositAddress(urls));
const got = await fetch(`https://ar-io.dev/${item.id}`, { redirect: "follow" });
console.log("gateway", got.status, (await got.text()).slice(0, 60));
